#!/usr/bin/env node
/**
 * Generate pamsurin-front gift share-card art, themes, and gift field-limit
 * constants from pamsurin-back canonical sources.
 *
 * Usage:
 *   node scripts/syncShareCard.mjs           # write front copies
 *   node scripts/syncShareCard.mjs --check   # exit 1 if committed front drifts
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const backRoot = resolve(__dirname, '..');
const frontRoot = resolve(backRoot, '../pamsurin-front');
const checkOnly = process.argv.includes('--check');

const backArtDir = resolve(backRoot, 'src/modules/gift/infrastructure/shareCardArt');
const frontArtDir = resolve(frontRoot, 'src/components/gift/shareCardArt');
const backInfra = resolve(backRoot, 'src/modules/gift/infrastructure');
const backDomain = resolve(backRoot, 'src/modules/gift/domain');
const frontGiftDir = resolve(frontRoot, 'src/components/gift');
const frontFieldLimitsPath = resolve(frontRoot, 'src/utils/fieldLimits.ts');
const backFieldLimitsPath = resolve(backRoot, 'src/utils/fieldLimits.ts');

const GENERATED_BANNER =
  '/* Generated by pamsurin-back `npm run sync:sharecard`. Do not edit by hand. */\n';

async function read(path) {
  return readFile(path, 'utf8');
}

function extractConst(source, name) {
  const match = source.match(
    new RegExp(`export const ${name} = ([\\s\\S]*?);\\n\\nexport type`),
  );
  if (match) return match[1].trim();
  const alt = source.match(new RegExp(`export const ${name} = ([\\s\\S]*?);\\s*$`));
  if (!alt) throw new Error(`Could not extract ${name}`);
  return alt[1].trim();
}

function extractGiftCommentLimits(fieldLimitsSource) {
  const length = fieldLimitsSource.match(
    /export const GIFT_COMMENT_MAX_LENGTH = (\d+);/,
  );
  const lines = fieldLimitsSource.match(/export const GIFT_COMMENT_MAX_LINES = (\d+);/);
  if (!length || !lines) {
    throw new Error('Could not read GIFT_COMMENT_MAX_* from back fieldLimits');
  }
  return { length: length[1], lines: lines[1] };
}

function patchFrontFieldLimits(source, { length, lines }) {
  let next = source.replace(
    /(\/\*\* Mirrors back-end `GIFT_COMMENT_MAX_LENGTH`\.\s*\*\/\nexport const FIELD_GIFT_COMMENT_MAX = )\d+(;)/,
    `$1${length}$2`,
  );
  next = next.replace(
    /(\/\*\* Mirrors back-end `GIFT_COMMENT_MAX_LINES` \(share-card print\)\.\s*\*\/\nexport const FIELD_GIFT_COMMENT_MAX_LINES = )\d+(;)/,
    `$1${lines}$2`,
  );
  if (!next.includes(`FIELD_GIFT_COMMENT_MAX = ${length}`)) {
    throw new Error('Failed to patch FIELD_GIFT_COMMENT_MAX in front fieldLimits');
  }
  if (!next.includes(`FIELD_GIFT_COMMENT_MAX_LINES = ${lines}`)) {
    throw new Error('Failed to patch FIELD_GIFT_COMMENT_MAX_LINES in front fieldLimits');
  }
  return next;
}

function buildFrontThemes({ stylesSource, fillSource, classicSource, moreSource }) {
  const stylesList = extractConst(stylesSource, 'GIFT_SHARE_CARD_STYLES');

  let fill = fillSource
    .replace(/^import[\s\S]*?;\n+/m, '')
    .replace(/export type GiftShareCardLayout/g, 'export type GiftShareCardLayout')
    .replace(/: GiftShareCardStyle/g, ': GiftShareCardStyle');

  // Drop the style import; front owns the style union from the styles list.
  fill = fill.replace(
    /import type \{ GiftShareCardStyle \} from '\.\.\/domain\/shareCardStyle\.js';\n*/,
    '',
  );

  const classicBody = classicSource
    .replace(/^import[\s\S]*?;\n+/m, '')
    .replace(/export const SHARE_CARD_THEMES_CLASSIC/, 'const SHARE_CARD_THEMES_CLASSIC');
  const moreBody = moreSource
    .replace(/^import[\s\S]*?;\n+/m, '')
    .replace(/export const SHARE_CARD_THEMES_MORE/, 'const SHARE_CARD_THEMES_MORE');

  return `${GENERATED_BANNER}
export const GIFT_SHARE_CARD_STYLES = ${stylesList};

export type GiftShareCardStyle = (typeof GIFT_SHARE_CARD_STYLES)[number];

${fill.trim()}

${classicBody.trim()}

${moreBody.trim()}

export const GIFT_SHARE_CARD_THEMES = {
  ...SHARE_CARD_THEMES_CLASSIC,
  ...SHARE_CARD_THEMES_MORE,
} as Record<GiftShareCardStyle, GiftShareCardTheme>;

export function giftShareCardTheme(style: GiftShareCardStyle): GiftShareCardTheme {
  return GIFT_SHARE_CARD_THEMES[style];
}
`;
}

function buildFrontArtBarrel(backBarrel) {
  const rewritten = backBarrel
    .replace(
      /import type \{ GiftShareCardStyle \} from '\.\.\/domain\/shareCardStyle\.js';/,
      "import type { GiftShareCardStyle } from './giftShareCardThemes';",
    )
    .replace(/from '\.\/shareCardArt\//g, "from './shareCardArt/")
    .replace(/\.js'/g, "'");
  return `${GENERATED_BANNER}${rewritten}`;
}

async function writeOrCheck(path, contents) {
  const normalized = contents.endsWith('\n') ? contents : `${contents}\n`;
  if (checkOnly) {
    let existing;
    try {
      existing = await read(path);
    } catch {
      console.error(`share-card check: missing ${path}`);
      return false;
    }
    if (existing !== normalized) {
      console.error(`share-card check: drift in ${path}`);
      return false;
    }
    return true;
  }
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, normalized, 'utf8');
  return true;
}

const artFiles = ['classic.ts', 'occasion.ts', 'myth.ts'];
const planned = [];

for (const name of artFiles) {
  const source = await read(resolve(backArtDir, name));
  planned.push([resolve(frontArtDir, name), `${GENERATED_BANNER}${source}`]);
}

const backBarrel = await read(resolve(backInfra, 'shareCardArt.ts'));
planned.push([resolve(frontGiftDir, 'shareCardArt.ts'), buildFrontArtBarrel(backBarrel)]);

const themes = buildFrontThemes({
  stylesSource: await read(resolve(backDomain, 'shareCardStyle.ts')),
  fillSource: await read(resolve(backInfra, 'shareCardThemeFill.ts')),
  classicSource: await read(resolve(backInfra, 'shareCardThemesClassic.ts')),
  moreSource: await read(resolve(backInfra, 'shareCardThemesMore.ts')),
});
planned.push([resolve(frontGiftDir, 'giftShareCardThemes.ts'), themes]);

const giftLimits = extractGiftCommentLimits(await read(backFieldLimitsPath));
const patchedFieldLimits = patchFrontFieldLimits(await read(frontFieldLimitsPath), giftLimits);
planned.push([frontFieldLimitsPath, patchedFieldLimits]);

let ok = true;
for (const [path, contents] of planned) {
  const passed = await writeOrCheck(path, contents);
  if (!passed) ok = false;
}

if (checkOnly) {
  if (!ok) {
    console.error(
      'share-card check failed. Run `npm run sync:sharecard` in pamsurin-back and commit the front copies.',
    );
    process.exitCode = 1;
  } else {
    console.log(`share-card check passed (${planned.length} front artifacts).`);
  }
} else {
  console.log(`sync:sharecard wrote ${planned.length} front artifacts under ${frontRoot}`);
}
