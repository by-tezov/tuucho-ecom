#!/usr/bin/env bash
# Stable cPanel Pipe to a Program entry point. Install as
# ~/bin/main-pipe-contact-dispatcher.sh. It selects the mailbox environment
# then hands the untouched message to the contact dispatcher.
set -euo pipefail

# Mail pipes must not leak messages, addresses, or configuration into cPanel
# delivery logs. Delivery failures are deliberately non-bouncing here.
log() { :; }

raw_file="$(mktemp "${TMPDIR:-/tmp}/main-pipe-contact.XXXXXX")"
trap 'rm -f "$raw_file"' EXIT
cat >"$raw_file"

header_values() {
  awk 'BEGIN { IGNORECASE=1 }
    /^(Delivered-To|X-Original-To|Envelope-To|To|X-Tuucho-Chat-Target):/ {
      sub(/^[^:]+:[[:space:]]*/, ""); print
    }' "$raw_file" | tr '[:upper:]' '[:lower:]'
}

# The piped mailbox addresses are the cPanel routes. Per-release environment
# is loaded only by the selected release dispatcher below.
preprod_address='preprod@shop.example'
prod_address='contact@shop.example'
preprod_address="${preprod_address,,}"
prod_address="${prod_address,,}"
headers="$(header_values)"

target=''
if grep -Fqi "$preprod_address" <<<"$headers"; then
  target=preprod
elif grep -Fqi "$prod_address" <<<"$headers"; then
  target=prod
fi

# A reply generated by the backend also contains this explicit target header.
if [[ -z "$target" ]]; then
  explicit_target="$(awk 'BEGIN { IGNORECASE=1 }
    /^X-Tuucho-Chat-Target:[[:space:]]*/ {
      sub(/^[^:]+:[[:space:]]*/, ""); print; exit
    }' "$raw_file" | tr -d '\r[:space:]' | tr '[:upper:]' '[:lower:]')"
  [[ "$explicit_target" =~ ^(preprod|prod)$ ]] && target="$explicit_target"
fi

target="${target:-prod}"

release_root="${HOME}/private_html/${target}"
release_dir="${release_root}/current"
dispatcher="${release_dir}/pipe/pipe-contact-dispatcher.sh"
[[ -x "$dispatcher" ]] || exit 0
TUCHO_CONTACT_TARGET="$target" TUCHO_CONTACT_RELEASE_DIR="$release_dir" "$dispatcher" <"$raw_file" || log "dispatcher failed target=$target"
exit 0
