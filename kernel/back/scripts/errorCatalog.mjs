#!/usr/bin/env node
/**
 * Every error code this API can return, and who reacts to it.
 *
 * There are 84 distinct codes across 664 `res.status(4xx|5xx)` sites,
 * explained in prose spread through `docs/api/`. An agent adding a branch had
 * no way to see the existing vocabulary, so it either grepped for a near match
 * or invented a synonym, and nothing noticed when the front kept branching on
 * a code the backend had stopped emitting.
 *
 * `--write` regenerates `docs/api/errors.json`: each code with the statuses it
 * is returned with, the files that emit it, and whether the front-end names it.
 *
 * `--check` (used by `npm run check:errors`) fails when that file is stale, and
 * when the front branches on a code no backend file emits, which is the
 * cross-repo break nothing else catches.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { extname, relative, resolve } from 'node:path';

const root = resolve('.');
const sourceRoot = resolve(root, 'src');
const frontRoot = resolve(root, '../front');
const outputPath = resolve(root, 'docs/api/errors.json');

async function walk(directory, extensions) {
  let entries;
  try {
    entries = await readdir(directory, { withFileTypes: true });
  } catch {
    return [];
  }
  const nested = await Promise.all(
    entries.map((entry) => {
      const path = resolve(directory, entry.name);
      if (entry.isDirectory()) return entry.name === 'node_modules' ? [] : walk(path, extensions);
      return extensions.includes(extname(entry.name)) ? [path] : [];
    }),
  );
  return nested.flat();
}

/** `res.status(404).json({ success: false, error: { code: 'not_found' } })` is
 * the shape `check:architecture` already enforces, so the status and the code
 * can be read off the same expression. A code emitted without a literal status
 * (a shared error mapper) is recorded with no status rather than guessed at. */
const STATUS_THEN_CODE = /status\((\d{3})\)[\s\S]{0,400}?code:\s*'([a-z_]+)'/g;
const ANY_CODE = /code:\s*'([a-z_]+)'/g;

const backFiles = await walk(sourceRoot, ['.ts']);
const codes = new Map();

function entryFor(code) {
  if (!codes.has(code)) codes.set(code, { statuses: new Set(), files: new Set(), front: [] });
  return codes.get(code);
}

for (const path of backFiles) {
  if (path.endsWith('.test.ts')) continue;
  const text = await readFile(path, 'utf8');
  const where = relative(root, path);
  for (const match of text.matchAll(STATUS_THEN_CODE)) {
    const entry = entryFor(match[2]);
    entry.statuses.add(Number(match[1]));
    entry.files.add(where);
  }
  for (const match of text.matchAll(ANY_CODE)) {
    entryFor(match[1]).files.add(where);
  }
}

/** What the front actually branches on. A code it names that nothing emits is
 * dead handling; a code nothing names is one the user sees only as a generic
 * failure, which is worth knowing but not worth failing over. */
const frontFiles = await walk(resolve(frontRoot, 'src'), ['.ts', '.tsx']);
const frontNamed = new Map();
for (const path of frontFiles) {
  const text = await readFile(path, 'utf8');
  const where = relative(frontRoot, path);
  for (const match of text.matchAll(/'([a-z][a-z_]{3,})'/g)) {
    const code = match[1];
    if (!codes.has(code)) continue;
    if (!frontNamed.has(code)) frontNamed.set(code, new Set());
    frontNamed.get(code).add(where);
  }
}

const catalog = {
  $comment:
    'Generated by `npm run sync:errors`. Every error code the API returns, the statuses it is returned with, the backend files that emit it, and the front-end files that branch on it. Do not edit by hand: `npm run check:errors` rejects a stale copy.',
  codes: Object.fromEntries(
    [...codes.entries()]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([code, entry]) => [
        code,
        {
          statuses: [...entry.statuses].sort((a, b) => a - b),
          emittedBy: [...entry.files].sort(),
          handledByFront: [...(frontNamed.get(code) ?? [])].sort(),
        },
      ]),
  ),
};

const rendered = `${JSON.stringify(catalog, null, 2)}\n`;

if (!process.argv.includes('--check')) {
  await writeFile(outputPath, rendered);
  const handled = Object.values(catalog.codes).filter((entry) => entry.handledByFront.length > 0).length;
  console.log(
    `Wrote docs/api/errors.json (${Object.keys(catalog.codes).length} codes, ${handled} named by the front).`,
  );
  process.exit(0);
}

const errors = [];
let current = '';
try {
  current = await readFile(outputPath, 'utf8');
} catch {
  errors.push('docs/api/errors.json is missing. Run `npm run sync:errors`.');
}
if (current && current !== rendered) {
  errors.push('docs/api/errors.json is stale. Run `npm run sync:errors`.');
}

if (errors.length > 0) {
  console.error(`Error catalog check failed (${errors.length}):`);
  for (const error of errors) console.error(`- ${error}`);
  process.exit(1);
}

const handled = Object.values(catalog.codes).filter((entry) => entry.handledByFront.length > 0).length;
console.log(`Error catalog check passed (${Object.keys(catalog.codes).length} codes, ${handled} named by the front).`);
